public class Casting {
    static void main() {
        //casting
        double price = 100.00;
        double finalPrice = 18 + price;
        System.out.println(finalPrice);

        //explicit casting
        int p = 100;
        int fp = p + (int)18.00;
        System.out.println(fp);

        //constants
        final float PI = 3.14F;

    }
}
